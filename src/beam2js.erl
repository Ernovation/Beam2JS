-module(beam2js).
-export([main/1, compile_file/2, compile_binary/1]).

-define(MAX_INPUT_SIZE, 32 * 1024 * 1024).

main(["serve" | Args]) ->
    beam2js_server:main(Args);
main([Input, Output]) ->
    case compile_file(Input, Output) of
        ok -> ok;
        {error, Reason} ->
            io:format(standard_error, "beam2js: ~ts: ~ts~n", [Input, Reason]),
            erlang:halt(1)
    end;
main(_) ->
    io:format(standard_error, "usage: beam2js INPUT.beam OUTPUT.mjs~n"
                              "       beam2js serve [OPTIONS]~n", []),
    erlang:halt(2).

compile_file(Input, Output) ->
    case file:read_file_info(Input) of
        {ok, Info} when element(2, Info) =< ?MAX_INPUT_SIZE ->
            case file:read_file(Input) of
                {ok, Binary} ->
                    case compile_binary(Binary) of
                        {ok, Source} -> write_output(Output, Source);
                        Error -> Error
                    end;
                {error, Reason} -> error_message("cannot read input: ~ts", [file:format_error(Reason)])
            end;
        {ok, _} -> {error, "input exceeds 32 MiB"};
        {error, Reason} -> error_message("cannot stat input: ~ts", [file:format_error(Reason)])
    end.

compile_binary(Binary) when is_binary(Binary), byte_size(Binary) =< ?MAX_INPUT_SIZE ->
    case erlang:system_info(otp_release) of
        "29" ->
            try beam_disasm:file(Binary) of
                {beam_file, Module, Exports, _Attributes, _CompileInfo, Functions} ->
                    try generate(Module, Exports, Functions) of
                        Source -> {ok, iolist_to_binary(Source)}
                    catch
                        throw:{unsupported, Detail} -> {error, lists:flatten(Detail)};
                        Class:Reason:Stack ->
                            error_message("internal compiler error (~p): ~tP at ~tP",
                                          [Class, Reason, 20, hd(Stack ++ [none]), 10])
                    end;
                Other -> error_message("cannot disassemble BEAM: ~tp", [Other])
            catch
                Class:Reason -> error_message("cannot disassemble BEAM (~p): ~tp", [Class, Reason])
            end;
        Release -> error_message("unsupported host OTP release ~s (requires OTP 29)", [Release])
    end;
compile_binary(Binary) when is_binary(Binary) ->
    {error, "input exceeds 32 MiB"}.

write_output(Output, Source) ->
    Temp = Output ++ "." ++ integer_to_list(erlang:unique_integer([positive, monotonic])) ++ ".tmp",
    case file:open(Temp, [write, binary, exclusive]) of
        {ok, File} ->
            Result = case file:write(File, Source) of
                ok -> file:close(File);
                {error, _} = WriteError ->
                    _ = file:close(File),
                    WriteError
            end,
            case Result of
                ok ->
                    case file:rename(Temp, Output) of
                        ok -> ok;
                        {error, RenameReason} ->
                            _ = file:delete(Temp),
                            error_message("cannot replace output: ~ts", [file:format_error(RenameReason)])
                    end;
                {error, WriteReason} ->
                    _ = file:delete(Temp),
                    error_message("cannot write output: ~ts", [file:format_error(WriteReason)])
            end;
        {error, OpenReason} ->
            error_message("cannot create temporary output: ~ts", [file:format_error(OpenReason)])
    end.

generate(Module, Exports, Functions) ->
    FunctionKeys = [{Name, Arity} || {function, Name, Arity, _, _} <- Functions],
    OnLoads = [Name || {function, Name, 0, _, Code} <- Functions, lists:member(on_load, Code)],
    Options = case OnLoads of
        [] -> <<>>;
        [OnLoad] -> [<<", {onLoad: ">>, string(OnLoad), <<"}">>];
        _ -> unsupported({module, 0}, 0, "multiple on_load functions")
    end,
    [<<"// Generated by beam2js; runtime ABI 26.\nexport function register(runtime) {\n">>,
     <<"  runtime.registerModule(26, ">>, string(Module), <<", [\n">>,
     lists:join(<<",\n">>, [function(Module, F, Exports, FunctionKeys) || F <- Functions]),
     <<"\n  ]">>, Options, <<");\n}\n">>].

function(Module, {function, Name, Arity, Entry, Instructions}, Exports, FunctionKeys) ->
    Context = {Name, Arity},
    Labels = maps:from_list([{Label, Index} ||
                             {{label, Label}, Index} <- indexed(Instructions)]),
    case maps:find(Entry, Labels) of
        {ok, EntryIndex} ->
            Exported = lists:member({Name, Arity, Entry}, Exports),
            [<<"    {name: ">>, string(Name), <<", arity: ">>, integer_to_list(Arity),
             <<", exported: ">>, atom_to_list(Exported),
             <<", run: (rt, x, state, budget, pid) => {\n      let pc = state ? state.pc : ">>,
             integer_to_list(EntryIndex),
             <<";\n      let y = state ? state.y : null;\n      const f = state?.f ?? [];\n      while (true) {\n">>,
             <<"        if (budget.remaining === 0) return {type: 'yield', state: {pc, y, f}, registers: x};\n">>,
             <<"        budget.remaining--;\n        switch (pc) {\n">>,
             [instruction(I, Index, Labels, Module, Context, FunctionKeys) ||
                 {I, Index} <- indexed(Instructions)],
             <<"          default: throw new Error('invalid BEAM program counter');\n">>,
             <<"        }\n      }\n    }}">>];
        error -> unsupported(Context, Entry, "missing entry label")
    end.

indexed(List) -> lists:zip(List, lists:seq(0, length(List) - 1)).

valid_heap_needs(Needs) ->
    valid_heap_needs(Needs, []).

valid_heap_needs([], _) -> true;
valid_heap_needs([{Kind, Count} | Rest], Seen)
  when (Kind =:= words orelse Kind =:= floats orelse Kind =:= funs),
       is_integer(Count), Count >= 0 ->
    not lists:member(Kind, Seen) andalso valid_heap_needs(Rest, [Kind | Seen]);
valid_heap_needs(_, _) -> false.

instruction(Instruction, Index, Labels, Module, Context, FunctionKeys) ->
    Body = case Instruction of
        {label, _} -> next(Index);
        {line, _} -> next(Index);
        on_load -> next(Index);
        nif_start -> next(Index);
        {func_info, {atom, Module}, {atom, Name}, Arity} when Context =:= {Name, Arity} ->
            <<"rt.raiseError(rt.atom('function_clause'));">>;
        {case_end, Source} ->
            raise_match(case_clause, Source, Context, Index);
        {'try', {y, Handler}, {f, Target}} ->
            [<<"rt.pushExceptionHandler(pid, {pc: ">>, target(Target, Labels, Context, Index),
             <<", kind: 'try', y}); rt.writeY(y, ">>, integer_to_list(Handler),
             <<", rt.atom('try')); ">>, next(Index)];
        {'catch', {y, Handler}, {f, Target}} ->
            [<<"rt.pushExceptionHandler(pid, {pc: ">>, target(Target, Labels, Context, Index),
             <<", kind: 'catch', y}); rt.writeY(y, ">>, integer_to_list(Handler),
             <<", rt.atom('catch')); ">>, next(Index)];
        try_end ->
            [<<"rt.popExceptionHandler(pid); ">>, next(Index)];
        {try_end, {y, _Handler}} ->
            [<<"rt.popExceptionHandler(pid); ">>, next(Index)];
        {try_case, {y, _Handler}} ->
            [<<"{ const exception = rt.takeException(pid); x[0] = exception[0]; x[1] = exception[1]; x[2] = exception[2]; } ">>, next(Index)];
        {catch_end, {y, _Handler}} ->
            [<<"x[0] = rt.catchEnd(pid, x[0]); ">>, next(Index)];
        {try_case_end, Source} ->
            raise_match(try_clause, Source, Context, Index);
        try_case_end ->
            [<<"rt.raiseError(rt.atom('try_clause'));">>];
        build_stacktrace ->
            [<<"x[0] = rt.buildStacktrace(x[0]); ">>, next(Index)];
        {recv_marker_reserve, {y, _} = Dest} ->
            [write_register(Dest, <<"rt.nil()">>, Context, Index), next(Index)];
        {recv_marker_reserve, {x, _} = Dest} ->
            [write_register(Dest, <<"rt.nil()">>, Context, Index), next(Index)];
        {recv_marker_bind, _Marker, _Reference} ->
            next(Index);
        {recv_marker_clear, _Reference} ->
            next(Index);
        {recv_marker_use, _Reference} ->
            next(Index);
        {raise, Class, Reason} ->
            [<<"rt.raiseException(">>, operand(Class, Context, Index), <<", ">>,
             operand(Reason, Context, Index), <<");">>];
        raw_raise ->
            [<<"rt.raiseExceptionFromRegisters(x);">>];
        {badmatch, Source} ->
            raise_match(badmatch, Source, Context, Index);
        if_end ->
            <<"rt.raiseError(rt.atom('if_clause'));">>;
        {move, Source, {x, Dest}} when is_integer(Dest), Dest >= 0, Dest < 1024 ->
            [<<"x[">>, integer_to_list(Dest), <<"] = ">>, operand(Source, Context, Index), <<"; ">>, next(Index)];
        {move, Source, {y, Dest}} when is_integer(Dest), Dest >= 0, Dest < 1024 ->
            [<<"rt.writeY(y, ">>, integer_to_list(Dest), <<", ">>, operand(Source, Context, Index),
             <<"); ">>, next(Index)];
        {swap, Left, Right} ->
            [<<"{ const left = ">>, register_operand(Left, Context, Index),
             <<"; const right = ">>, register_operand(Right, Context, Index), <<"; ">>,
             write_register(Left, <<"right">>, Context, Index),
             write_register(Right, <<"left">>, Context, Index), <<"} ">>, next(Index)];
        {fconv, Source, {fr, Dest}} when is_integer(Dest), Dest >= 0, Dest < 1023 ->
            [<<"{ const value = rt.guardArithmetic('float', ">>, operand(Source, Context, Index),
             <<"); if (value === null) rt.raiseError(rt.atom('badarith')); f[">>,
             integer_to_list(Dest), <<"] = rt.floatValue(value); } ">>, next(Index)];
        {fmove, {fr, Source}, Dest} when is_integer(Source), Source >= 0, Source < 1023 ->
            [write_register(Dest, [<<"rt.float(rt.readF(f, ">>, integer_to_list(Source), <<"))">>],
                            Context, Index), next(Index)];
        {fmove, Source, {fr, Dest}} when is_integer(Dest), Dest >= 0, Dest < 1023 ->
            [<<"f[">>, integer_to_list(Dest), <<"] = rt.floatValue(">>,
             operand(Source, Context, Index), <<"); ">>, next(Index)];
        {bif, Op, {f, 0}, [{fr, Left}, {fr, Right}], {fr, Dest}}
          when (Op =:= fadd orelse Op =:= fsub orelse Op =:= fmul orelse Op =:= fdiv),
               is_integer(Left), Left >= 0, Left < 1023,
               is_integer(Right), Right >= 0, Right < 1023,
               is_integer(Dest), Dest >= 0, Dest < 1023 ->
            Operator = case Op of
                fadd -> <<" + ">>;
                fsub -> <<" - ">>;
                fmul -> <<" * ">>;
                fdiv -> <<" / ">>
            end,
            [<<"{ const result = rt.readF(f, ">>, integer_to_list(Left),
             <<")">>, Operator, <<"rt.readF(f, ">>, integer_to_list(Right),
             <<"); if (!Number.isFinite(result)) rt.raiseError(rt.atom('badarith')); f[">>,
             integer_to_list(Dest), <<"] = result; } ">>, next(Index)];
        {bif, fnegate, {f, 0}, [{fr, Source}], {fr, Dest}}
          when is_integer(Source), Source >= 0, Source < 1023,
               is_integer(Dest), Dest >= 0, Dest < 1023 ->
            [<<"f[">>, integer_to_list(Dest), <<"] = -rt.readF(f, ">>,
             integer_to_list(Source), <<"); ">>, next(Index)];
        {allocate, Size, Live}
          when is_integer(Size), Size >= 0, Size =< 1024,
               is_integer(Live), Live >= 0, Live =< 1024 ->
            [<<"y = rt.allocate(y, ">>, integer_to_list(Size), <<"); ">>, next(Index)];
        {allocate_heap, Size, Words, Live}
          when is_integer(Size), Size >= 0, Size =< 1024, is_integer(Words), Words >= 0,
               is_integer(Live), Live >= 0, Live =< 1024 ->
            [<<"y = rt.allocate(y, ">>, integer_to_list(Size), <<"); ">>, next(Index)];
        {allocate_heap, Size, {alloc, Needs}, Live}
          when is_integer(Size), Size >= 0, Size =< 1024, is_list(Needs),
               is_integer(Live), Live >= 0, Live =< 1024 ->
            case valid_heap_needs(Needs) of
                true -> [<<"y = rt.allocate(y, ">>, integer_to_list(Size), <<"); ">>, next(Index)];
                false -> unsupported(Context, Index, "invalid heap allocation list")
            end;
        {deallocate, Size} when is_integer(Size), Size >= 0, Size =< 1024 ->
            [deallocate(Size), next(Index)];
        {init_yregs, {list, Registers}} when is_list(Registers), Registers =/= [] ->
            init_yregs(Registers, Context, Index);
        {trim, Count, Remaining}
          when is_integer(Count), Count >= 0, Count =< 1024,
               is_integer(Remaining), Remaining >= 0, Remaining =< 1024 ->
            [<<"y = rt.trim(y, ">>, integer_to_list(Count), <<", ">>,
             integer_to_list(Remaining), <<"); ">>, next(Index)];
        {test, Op, {f, Target}, [Left, Right]}
          when Op =:= is_eq_exact; Op =:= is_ne_exact; Op =:= is_eq;
               Op =:= is_ne; Op =:= is_lt; Op =:= is_ge ->
            Condition = comparison(Op, operand(Left, Context, Index), operand(Right, Context, Index)),
            branch(Condition, Target, Index, Labels, Context);
        {test, Op, {f, Target}, [Source]}
          when Op =:= is_integer; Op =:= is_number; Op =:= is_atom; Op =:= is_function;
               Op =:= is_boolean; Op =:= is_float; Op =:= is_nil;
               Op =:= is_list; Op =:= is_nonempty_list; Op =:= is_tuple;
               Op =:= is_binary; Op =:= is_bitstr; Op =:= is_pid; Op =:= is_reference;
               Op =:= is_map; Op =:= is_function ->
            Condition = type_test(Op, Source, Context, Index),
            branch(Condition, Target, Index, Labels, Context);
        {test, test_arity, {f, Target}, [Source, Arity]}
          when is_integer(Arity), Arity >= 0, Arity =< 9007199254740991 ->
            Condition = [<<"rt.tupleSize(">>, operand(Source, Context, Index), <<") === ">>,
                         integer_to_list(Arity)],
            branch(Condition, Target, Index, Labels, Context);
        {test, is_function, {f, Target}, [Source]}
          when is_integer(Target), Target >= 0 ->
            branch(type_test(is_function, Source, Context, Index), Target, Index, Labels, Context);
        {test, is_tagged_tuple, {f, Target}, [Source, Arity, {atom, Tag}]}
          when is_integer(Arity), Arity > 0, Arity =< 9007199254740991, is_atom(Tag) ->
            Condition = [<<"(value => rt.isType('is_tuple', value) && rt.tupleSize(value) === ">>,
                         integer_to_list(Arity), <<" && rt.equalExact(rt.tupleElement(value, 1), rt.atom(">>,
                         string(Tag), <<")))(">>, operand(Source, Context, Index), <<")">>],
            branch(Condition, Target, Index, Labels, Context);
        {bif, Op, {f, 0}, [Source], Dest}
          when (Op =:= is_integer orelse Op =:= is_number orelse Op =:= is_atom orelse
                Op =:= is_boolean orelse Op =:= is_float orelse Op =:= is_list orelse
                Op =:= is_tuple orelse Op =:= is_binary orelse Op =:= is_bitstring orelse
                Op =:= is_pid orelse Op =:= is_reference orelse Op =:= is_map orelse
                Op =:= is_function) ->
            Value = [<<"rt.atom(">>, type_test(Op, Source, Context, Index),
                     <<" ? 'true' : 'false')">>],
            [write_register(Dest, Value, Context, Index), next(Index)];
        {bif, Op, {f, Target}, [Key, Map], Dest}
          when Op =:= map_get; Op =:= is_map_key ->
            guard_bif(Op, [Key, Map], Dest, Target, Index, Labels, Context);
        {bif, is_function, {f, 0}, [Source], Dest} ->
            [write_register(Dest, [<<"rt.atom(rt.isType('is_function', ">>, operand(Source, Context, Index), <<") ? 'true' : 'false')">>], Context, Index), next(Index)];
        {bif, is_map, {f, 0}, [Map], Dest} ->
            [write_register(Dest, [<<"rt.atom(rt.isType('is_map', ">>, operand(Map, Context, Index), <<") ? 'true' : 'false')">>], Context, Index), next(Index)];
        {bif, Op, {f, Target}, [Map], Dest}
          when Op =:= map_size ->
            guard_bif(Op, [Map], Dest, Target, Index, Labels, Context);
        {gc_bif, Op, {f, Target}, Live, [Map], Dest}
          when Op =:= map_size, is_integer(Live), Live >= 0, Live =< 1024 ->
            guard_bif(Op, [Map], Dest, Target, Index, Labels, Context);
        {bif, raise, {f, 0}, [RawStack, Reason], _Dest} ->
            [<<"rt.raiseRaw(">>, operand(RawStack, Context, Index), <<", ">>,
             operand(Reason, Context, Index), <<");">>];
        {bif, Op, {f, 0}, [Left, Right], Dest}
          when Op =:= '=:='; Op =:= '=/='; Op =:= '=='; Op =:= '/=';
               Op =:= '<'; Op =:= '>='; Op =:= '>'; Op =:= '=<' ->
            {Test, First, Second} = case Op of
                '=:=' -> {is_eq_exact, Left, Right};
                '=/=' -> {is_ne_exact, Left, Right};
                '==' -> {is_eq, Left, Right};
                '/=' -> {is_ne, Left, Right};
                '<' -> {is_lt, Left, Right};
                '>=' -> {is_ge, Left, Right};
                '>' -> {is_lt, Right, Left};
                '=<' -> {is_ge, Right, Left}
            end,
            Condition = comparison(Test, operand(First, Context, Index), operand(Second, Context, Index)),
            Value = [<<"rt.atom(">>, Condition, <<" ? 'true' : 'false')">>],
            [write_register(Dest, Value, Context, Index), next(Index)];
        {bif, self, nofail, [], Dest} ->
            [write_register(Dest, <<"pid">>, Context, Index), next(Index)];
        {bif, get, {f, 0}, [Source], Dest} ->
            [write_register(Dest, [<<"rt.getProcessDictionary(pid, ">>,
                                   operand(Source, Context, Index), <<")">>],
                            Context, Index), next(Index)];
        send ->
            [<<"x[0] = rt.sendPidMessage(rt.read(x, 0), rt.read(x, 1)); ">>, next(Index)];
        {loop_rec, {f, Target}, {x, Dest} = Register}
          when is_integer(Dest), Dest >= 0, Dest < 1024 ->
            [<<"{ const message = rt.receiveMessage(pid); if (message === null) { pc = ">>,
             target(Target, Labels, Context, Index), <<"; } else { ">>,
             write_register(Register, <<"message">>, Context, Index),
             <<"pc = ">>, integer_to_list(Index + 1), <<"; } break; }">>];
        {loop_rec_end, {f, Target}} ->
            [<<"rt.advanceMessage(pid); pc = ">>, target(Target, Labels, Context, Index), <<"; break;">>];
        remove_message ->
            [<<"rt.removeMessage(pid); ">>, next(Index)];
        timeout ->
            [<<"rt.timeoutMessage(pid); ">>, next(Index)];
        {wait, {f, Target}} ->
            [<<"return {type: 'wait', state: {pc: ">>, target(Target, Labels, Context, Index),
             <<", y, f}, registers: x};">>];
        {wait_timeout, {f, Target}, Time} ->
            [<<"return {type: 'wait_timeout', state: {pc: ">>, target(Target, Labels, Context, Index),
             <<", y, f}, timeoutPc: ">>, integer_to_list(Index + 1), <<", timeout: ">>,
             operand(Time, Context, Index), <<", registers: x};">>];
        {bif, Op, {f, Target}, [Source], Dest}
          when Op =:= hd; Op =:= tl; Op =:= tuple_size; Op =:= 'not' ->
            guard_bif(Op, [Source], Dest, Target, Index, Labels, Context);
        {bif, Op, {f, Target}, [Left, Right], Dest}
          when Op =:= 'and'; Op =:= 'or'; Op =:= 'xor' ->
            guard_bif(Op, [Left, Right], Dest, Target, Index, Labels, Context);
        {bif, element, {f, Target}, [Position, Source], Dest} ->
            guard_bif(element, [Position, Source], Dest, Target, Index, Labels, Context);
        {gc_bif, Op, {f, Target}, Live, [Source], Dest}
          when (Op =:= length orelse Op =:= bit_size orelse Op =:= byte_size orelse Op =:= 'bnot' orelse
                Op =:= '-' orelse Op =:= abs orelse Op =:= trunc orelse Op =:= round orelse
                Op =:= floor orelse Op =:= ceil orelse Op =:= float),
               is_integer(Live), Live >= 0, Live =< 1024 ->
            guard_bif(Op, [Source], Dest, Target, Index, Labels, Context);
        {gc_bif, Op, {f, Target}, Live, [Left, Right], Dest}
          when (Op =:= binary_part orelse Op =:= 'band' orelse Op =:= 'bor' orelse Op =:= 'bxor' orelse
                Op =:= 'div' orelse Op =:= 'rem' orelse Op =:= '+' orelse Op =:= '-' orelse
                Op =:= '*' orelse Op =:= '/'),
               is_integer(Live), Live >= 0, Live =< 1024 ->
            guard_bif(Op, [Left, Right], Dest, Target, Index, Labels, Context);
        {gc_bif, binary_part, {f, Target}, Live, [Source, Position, Length], Dest}
          when is_integer(Live), Live >= 0, Live =< 1024 ->
            guard_bif(binary_part, [Source, Position, Length], Dest, Target, Index, Labels, Context);
        {test_heap, Words, Live}
          when is_integer(Words), Words >= 0, is_integer(Live), Live >= 0, Live =< 1024 ->
            next(Index);
        {test_heap, {alloc, Needs}, Live}
          when is_list(Needs), is_integer(Live), Live >= 0, Live =< 1024 ->
            case valid_heap_needs(Needs) of
                true -> next(Index);
                false -> unsupported(Context, Index, "invalid heap allocation list")
            end;
        {put_list, Head, Tail, Dest} ->
            Value = [<<"rt.cons(">>, operand(Head, Context, Index), <<", ">>,
                     operand(Tail, Context, Index), <<")">>],
            [write_register(Dest, Value, Context, Index), next(Index)];
        {get_hd, Source, Dest} ->
            Value = [<<"rt.listHead(">>, operand(Source, Context, Index), <<")">>],
            [write_register(Dest, Value, Context, Index), next(Index)];
        {get_tl, Source, Dest} ->
            Value = [<<"rt.listTail(">>, operand(Source, Context, Index), <<")">>],
            [write_register(Dest, Value, Context, Index), next(Index)];
        {get_list, Source, Head, Tail} when Head =/= Tail ->
            [<<"{ const list = ">>, operand(Source, Context, Index), <<"; ">>,
             write_register(Head, <<"rt.listHead(list)">>, Context, Index),
             write_register(Tail, <<"rt.listTail(list)">>, Context, Index),
             <<"} ">>, next(Index)];
        {put_tuple2, Dest, {list, Elements}} when is_list(Elements) ->
            Value = [<<"rt.tuple([">>,
                     lists:join(<<", ">>, [operand(E, Context, Index) || E <- Elements]),
                     <<"])">>],
            [write_register(Dest, Value, Context, Index), next(Index)];
        {make_fun3, {Module, Name, Arity}, _OldIndex, _Dst, Source, {list, Environment}}
          when is_integer(Arity), Arity >= 0, is_list(Environment) ->
            [write_register(Source, [<<"rt.makeFun(">>, string(Module), <<", ">>, string(Name), <<", ">>,
                                     integer_to_list(Arity), <<", [">>,
                                     lists:join(<<", ">>, [operand(E, Context, Index) || E <- Environment]),
                                     <<"])">>], Context, Index), next(Index)];
        {make_fun3, {Module, Name, Arity}, _OldIndex, _Dst, {x, Dest}, {list, Environment}}
          when is_integer(Arity), Arity >= 0, is_list(Environment) ->
            [write_register({x, Dest}, [<<"rt.makeFun(">>, string(Module), <<", ">>, string(Name), <<", ">>,
                                         integer_to_list(Arity), <<", [">>,
                                         lists:join(<<", ">>, [operand(E, Context, Index) || E <- Environment]),
                                         <<"])">>], Context, Index), next(Index)];
        {call_fun, Arity}
          when is_integer(Arity), Arity >= 0, Arity < 1024 ->
            [<<"return {type: 'fun_call', fun: rt.read(x, ">>, integer_to_list(Arity), <<"), args: rt.args(x, ">>, integer_to_list(Arity), <<"), state: {pc: ">>, integer_to_list(Index + 1), <<", y}, y: y};">>];
        {put_map_assoc, {f, _}, Source, Dest, Size, {list, Pairs}}
          when is_integer(Size), Size >= 0, is_list(Pairs) ->
            Entries = lists:join(<<", ">>, [[<<"[">>, operand(K, Context, Index), <<", ">>,
                                               operand(V, Context, Index), <<"]">>] ||
                                              {K, V} <- pairs(Pairs)]),
            Value = [<<"rt.mapPut(">>, operand(Source, Context, Index), <<", [">>, Entries, <<"])">>],
            [write_register(Dest, Value, Context, Index), next(Index)];
        {put_map_exact, {f, _}, Source, Dest, Size, {list, Pairs}}
          when is_integer(Size), Size >= 0, is_list(Pairs) ->
            Entries = lists:join(<<", ">>, [[<<"[">>, operand(K, Context, Index), <<", ">>,
                                               operand(V, Context, Index), <<"]">>] ||
                                              {K, V} <- pairs(Pairs)]),
            Value = [<<"rt.mapPutExact(">>, operand(Source, Context, Index), <<", [">>, Entries, <<"])">>],
            [write_register(Dest, Value, Context, Index), next(Index)];
        {has_map_fields, {f, Fail}, Source, {list, Fields}}
          when is_list(Fields) ->
            has_map_fields(Source, Fail, Fields, Index, Labels, Context);
        {get_map_elements, {f, Fail}, Source, {list, Fields}}
          when is_list(Fields) ->
            get_map_elements(Source, Fail, Fields, Index, Labels, Context);
        {get_tuple_element, Source, Element, Dest}
          when is_integer(Element), Element >= 0, Element < 9007199254740991 ->
            Value = [<<"rt.tupleElement(">>, operand(Source, Context, Index),
                     <<", ">>, integer_to_list(Element + 1), <<")">>],
            [write_register(Dest, Value, Context, Index), next(Index)];
        {select_val, Source, {f, Fail}, {list, Choices}} when is_list(Choices) ->
            selection(value, Source, Fail, Choices, Labels, Context, Index);
        {select_tuple_arity, Source, {f, Fail}, {list, Choices}} when is_list(Choices) ->
            selection(arity, Source, Fail, Choices, Labels, Context, Index);
        {jump, {f, Target}} ->
            [<<"pc = ">>, target(Target, Labels, Context, Index), <<"; break;">>];
        {call, Arity, {Module, Name, Arity}} when is_integer(Arity), Arity >= 0, Arity =< 255 ->
            case lists:member({Name, Arity}, FunctionKeys) of
                true -> call(Module, Name, Arity, false, Index);
                false -> unsupported(Context, Index, "unknown local function")
            end;
        {call_ext, Arity, {extfunc, ExtModule, Name, Arity}}
          when is_integer(Arity), Arity >= 0, Arity =< 255 ->
            call(ExtModule, Name, Arity, true, Index);
        {call_last, Arity, {Module, Name, Arity}, Size}
          when is_integer(Arity), Arity >= 0, Arity =< 255,
               is_integer(Size), Size >= 0, Size =< 1024 ->
            case lists:member({Name, Arity}, FunctionKeys) of
                true -> [deallocate(Size), tail_call(Module, Name, Arity, false)];
                false -> unsupported(Context, Index, "unknown local function")
            end;
        {call_ext_last, Arity, {extfunc, ExtModule, Name, Arity}, Size}
          when is_integer(Arity), Arity >= 0, Arity =< 255,
               is_integer(Size), Size >= 0, Size =< 1024 ->
            [deallocate(Size), tail_call(ExtModule, Name, Arity, true)];
        {call_only, Arity, {Module, Name, Arity}} when is_integer(Arity), Arity >= 0, Arity =< 255 ->
            case lists:member({Name, Arity}, FunctionKeys) of
                true -> tail_call(Module, Name, Arity, false);
                false -> unsupported(Context, Index, "unknown local function")
            end;
        {call_ext_only, Arity, {extfunc, ExtModule, Name, Arity}}
          when is_integer(Arity), Arity >= 0, Arity =< 255 ->
            tail_call(ExtModule, Name, Arity, true);
        {apply, Arity} when is_integer(Arity), Arity >= 0, Arity =< 255 ->
            [<<"if (y === null) throw new Error('call without allocated stack frame'); ">>,
             <<"return {type: 'call', module: 'erlang', name: 'apply', args: ">>, apply_args(Arity),
             <<", external: true, state: {pc: ">>, integer_to_list(Index + 1), <<", y}};">>];
        {apply_last, Arity, Size}
          when is_integer(Arity), Arity >= 0, Arity =< 255,
               is_integer(Size), Size >= 0, Size =< 1024 ->
            [deallocate(Size),
             <<"return {type: 'tail', module: 'erlang', name: 'apply', args: ">>, apply_args(Arity),
             <<", external: true};">>];
        return -> <<"if (y !== null) throw new Error('return with allocated stack frame'); return {type: 'return', value: rt.read(x, 0)};">>;
        _ -> unsupported(Context, Index, io_lib:format("unsupported instruction ~tp", [Instruction]))
    end,
    [<<"          case ">>, integer_to_list(Index), <<": ">>, Body, <<"\n">>].

next(Index) -> [<<"pc = ">>, integer_to_list(Index + 1), <<"; break;">>].

raise_match(Reason, Source, Context, Index) ->
    [<<"rt.raiseError(rt.tuple([rt.atom(">>, string(Reason), <<"), ">>,
     operand(Source, Context, Index), <<"]));">>].

type_test(Op, Source, Context, Index) ->
    [<<"rt.isType(">>, string(Op), <<", ">>, operand(Source, Context, Index), <<")">>].

guard_bif(Op, Sources, Dest, Target, Index, Labels, Context) ->
    Values = [operand(Source, Context, Index) || Source <- Sources],
    {Declarations, Condition, Result} = case {Op, Values} of
        {ListTuple, _} when ListTuple =:= hd; ListTuple =:= tl; ListTuple =:= length;
                            ListTuple =:= tuple_size; ListTuple =:= element ->
            {[<<"const result = rt.guardListTuple(">>, string(ListTuple), <<", ">>,
              lists:join(<<", ">>, Values), <<"); ">>],
             <<"result !== null">>, <<"result">>};
        {'not', [Value]} ->
            {[<<"const value = ">>, Value, <<"; ">>],
             <<"rt.isType('is_boolean', value)">>,
             <<"rt.atom(value === rt.atom('false') ? 'true' : 'false')">>};
        {Boolean, [Left, Right]} when Boolean =:= 'and'; Boolean =:= 'or'; Boolean =:= 'xor' ->
            Expression = case Boolean of
                'and' -> <<"left === rt.atom('true') && right === rt.atom('true')">>;
                'or' -> <<"left === rt.atom('true') || right === rt.atom('true')">>;
                'xor' -> <<"left !== right">>
            end,
            {[<<"const left = ">>, Left, <<"; const right = ">>, Right, <<"; ">>],
             <<"rt.isType('is_boolean', left) && rt.isType('is_boolean', right)">>,
             [<<"rt.atom(">>, Expression, <<" ? 'true' : 'false')">>]};
        {map_get, [Key, Map]} ->
            {[<<"const value = rt.mapGet(">>, Map, <<", ">>, Key, <<"); ">>],
             <<"value !== null">>, <<"value">>};
        {is_map_key, [Key, Map]} ->
            {[<<"const value = rt.mapGet(">>, Map, <<", ">>, Key, <<"); ">>],
             <<"rt.isType('is_map', ">>, Map, <<")">>,
             <<"rt.atom(value !== null ? 'true' : 'false')">>};
        {map_size, [Map]} ->
            {[<<"const result = rt.isType('is_map', ">>, Map, <<") ? rt.mapSize(">>, Map, <<") : null; ">>],
             <<"result !== null">>, <<"result">>};
        {is_map, [Map]} ->
            {[<<"const result = rt.isType('is_map', ">>, Map, <<"); ">>],
             <<"true">>, <<"rt.atom(result ? 'true' : 'false')">>};
        {'bnot', [Value]} ->
            {[<<"const value = ">>, Value, <<"; ">>],
             <<"typeof value === 'bigint'">>, <<"~value">>};
        {Bitstring, _} when Bitstring =:= bit_size; Bitstring =:= byte_size; Bitstring =:= binary_part ->
            {[<<"const result = rt.guardBitstringBif(">>, string(Bitstring), <<", ">>,
              lists:join(<<", ">>, Values), <<"); ">>],
             <<"result !== null">>, <<"result">>};
        {'-', [Value]} ->
            {[<<"const result = rt.guardArithmetic('neg', ">>, Value, <<"); ">>],
             <<"result !== null">>, <<"result">>};
        {Unary, [Value]} when Unary =:= abs; Unary =:= trunc; Unary =:= round;
                              Unary =:= floor; Unary =:= ceil; Unary =:= float ->
            {[<<"const result = rt.guardArithmetic(">>, string(Unary), <<", ">>, Value, <<"); ">>],
             <<"result !== null">>, <<"result">>};
        {Arithmetic, [Left, Right]}
          when Arithmetic =:= '+'; Arithmetic =:= '-'; Arithmetic =:= '*'; Arithmetic =:= '/' ->
            {[<<"const result = rt.guardArithmetic(">>, string(Arithmetic), <<", ">>, Left,
              <<", ">>, Right, <<"); ">>],
             <<"result !== null">>, <<"result">>};
        {IntegerOp, [Left, Right]}
          when IntegerOp =:= 'band'; IntegerOp =:= 'bor'; IntegerOp =:= 'bxor';
               IntegerOp =:= 'div'; IntegerOp =:= 'rem' ->
            {Operator, Nonzero} = case IntegerOp of
                'band' -> {<<" & ">>, <<>>};
                'bor' -> {<<" | ">>, <<>>};
                'bxor' -> {<<" ^ ">>, <<>>};
                'div' -> {<<" / ">>, <<" && right !== 0n">>};
                'rem' -> {<<" % ">>, <<" && right !== 0n">>}
            end,
            {[<<"const left = ">>, Left, <<"; const right = ">>, Right, <<"; ">>],
             [<<"typeof left === 'bigint' && typeof right === 'bigint'">>, Nonzero],
             [<<"left">>, Operator, <<"right">>]}
    end,
    Failure = case {Op, Target} of
        {FailureOp, 0} when FailureOp =:= '+'; FailureOp =:= '-';
                            FailureOp =:= '*'; FailureOp =:= '/';
                            FailureOp =:= 'div'; FailureOp =:= 'rem';
                            FailureOp =:= 'band'; FailureOp =:= 'bor';
                            FailureOp =:= 'bxor'; FailureOp =:= 'bnot' ->
            <<"rt.raiseError(rt.atom('badarith'));">>;
        {map_get, 0} -> <<"rt.raiseError(rt.atom('badkey'));">>;
        {is_map_key, 0} -> <<"rt.raiseError(rt.atom('badmap'));">>;
        {map_size, 0} -> <<"rt.raiseError(rt.atom('badmap'));">>;
        {FailureOp, 0} when FailureOp =:= hd; FailureOp =:= tl; FailureOp =:= length;
                            FailureOp =:= tuple_size; FailureOp =:= element;
                            FailureOp =:= abs; FailureOp =:= trunc; FailureOp =:= round;
                            FailureOp =:= floor; FailureOp =:= ceil; FailureOp =:= float;
                            FailureOp =:= bit_size; FailureOp =:= byte_size;
                            FailureOp =:= binary_part; FailureOp =:= 'not';
                            FailureOp =:= 'and'; FailureOp =:= 'or'; FailureOp =:= 'xor' ->
            <<"rt.raiseError(rt.atom('badarg'));">>;
        _ -> [<<"pc = ">>, target(Target, Labels, Context, Index), <<";">>]
    end,
    [<<"{ ">>, Declarations, <<"if (">>, Condition, <<") { ">>,
     write_register(Dest, Result, Context, Index),
     <<"pc = ">>, integer_to_list(Index + 1), <<"; } else { ">>,
     Failure, <<" } break; }">>].

pairs(List) -> pairs(List, []).
pairs([], Acc) -> lists:reverse(Acc);
pairs([Key, Value | Rest], Acc) -> pairs(Rest, [{Key, Value} | Acc]).

has_map_fields(Source, Fail, Fields, Index, Labels, Context) ->
    Checks = [[<<"rt.mapGet(">>, operand(Source, Context, Index), <<", ">>,
               operand(Key, Context, Index), <<") !== null">>] || Key <- Fields],
    [<<"{ if (">>, lists:join(<<" && ">>, Checks), <<") { pc = ">>,
     integer_to_list(Index + 1), <<"; } else { pc = ">>,
     target(Fail, Labels, Context, Index), <<"; } break; }">>].

get_map_elements(Source, Fail, Fields, Index, Labels, Context) ->
    {Declarations, Writes, Checks} = get_map_fields(Source, Fields, [], [], [], Context, Index),
    [<<"{ ">>, Declarations,
     <<"if (">>, lists:join(<<" && ">>, Checks), <<") { ">>, Writes,
     <<"pc = ">>, integer_to_list(Index + 1), <<"; } else { pc = ">>,
     target(Fail, Labels, Context, Index), <<"; } break; }">>].

get_map_fields(_, [], Declarations, Writes, Checks, _, _) ->
    {lists:reverse(Declarations), lists:reverse(Writes), lists:reverse(Checks)};
get_map_fields(Source, [Key, Dest | Rest], Declarations, Writes, Checks, Context, Index) ->
    Name = [<<"const mapValue">>, integer_to_list(length(Declarations)), <<" = rt.mapGet(">>,
            operand(Source, Context, Index), <<", ">>, operand(Key, Context, Index), <<"); ">>],
    Write = write_register(Dest, [<<"mapValue">>, integer_to_list(length(Declarations))], Context, Index),
    Check = [<<"mapValue">>, integer_to_list(length(Declarations)), <<" !== null">>],
    get_map_fields(Source, Rest, [Name | Declarations], [Write | Writes], [Check | Checks], Context, Index).

selection(Kind, Source, Fail, Choices, Labels, Context, Index) ->
    Value = operand(Source, Context, Index),
    Read = case Kind of
        value -> Value;
        arity -> [<<"rt.tupleSize(">>, Value, <<")">>]
    end,
    Cases = selection_cases(Kind, Choices, undefined, #{}, Labels, Context, Index),
    [<<"{ const value = ">>, Read, <<"; ">>, Cases, <<"pc = ">>,
     target(Fail, Labels, Context, Index), <<"; break; }">>].

selection_cases(_, [], _, _, _, _, _) -> [];
selection_cases(Kind, [Choice, {f, Label} | Rest], Expected, Seen, Labels, Context, Index) ->
    {ChoiceKind, Key} = selection_choice(Kind, Choice, Context, Index),
    case (Expected =:= undefined orelse Expected =:= ChoiceKind) andalso
         not maps:is_key(Key, Seen) of
        true -> ok;
        false -> unsupported(Context, Index, "mixed or duplicate selection choices")
    end,
    Condition = case Kind of
        value -> [<<"rt.equalExact(value, ">>, operand(Choice, Context, Index), <<")">>];
        arity -> [<<"value === ">>, integer_to_list(Key)]
    end,
    [<<"if (">>, Condition, <<") { pc = ">>, target(Label, Labels, Context, Index),
     <<"; break; } ">>,
     selection_cases(Kind, Rest, ChoiceKind, Seen#{Key => true}, Labels, Context, Index)];
selection_cases(_, _, _, _, _, Context, Index) ->
    unsupported(Context, Index, "invalid selection choice list").

selection_choice(arity, Key, _, _) when is_integer(Key), Key >= 0, Key =< 9007199254740991 ->
    {arity, Key};
selection_choice(value, {atom, Key}, _, _) when is_atom(Key) -> {atom, Key};
selection_choice(value, {integer, Key}, _, _) when is_integer(Key) -> {integer, Key};
selection_choice(value, {float, Key}, _, _) when is_float(Key) -> {float, Key};
selection_choice(value, {literal, Key}, _, _) when is_atom(Key) -> {atom, Key};
selection_choice(value, {literal, Key}, _, _) when is_integer(Key) -> {integer, Key};
selection_choice(value, {literal, Key}, _, _) when is_float(Key) -> {float, Key};
selection_choice(_, _, Context, Index) -> unsupported(Context, Index, "invalid selection choice").

comparison(Op, Left, Right) ->
    {Prefix, Function, Suffix} = case Op of
        is_eq_exact -> {<<>>, <<"equalExact">>, <<>>};
        is_ne_exact -> {<<"!">>, <<"equalExact">>, <<>>};
        is_eq -> {<<>>, <<"equalNumeric">>, <<>>};
        is_ne -> {<<"!">>, <<"equalNumeric">>, <<>>};
        is_lt -> {<<>>, <<"compare">>, <<" < 0">>};
        is_ge -> {<<>>, <<"compare">>, <<" >= 0">>}
    end,
    [Prefix, <<"rt.">>, Function, <<"(">>, Left, <<", ">>, Right, <<")">>, Suffix].

branch(Condition, Target, Index, Labels, Context) ->
    [<<"pc = ">>, Condition, <<" ? ">>, integer_to_list(Index + 1), <<" : ">>,
     target(Target, Labels, Context, Index), <<"; break;">>].

tail_call(Module, Name, Arity, External) ->
    [<<"return {type: 'tail', module: ">>, string(Module), <<", name: ">>, string(Name),
     <<", args: rt.args(x, ">>, integer_to_list(Arity), <<"), external: ">>,
     atom_to_list(External), <<"};">>].

call(Module, Name, Arity, External, Index) ->
    [<<"if (y === null) throw new Error('call without allocated stack frame'); ">>,
     <<"return {type: 'call', module: ">>, string(Module), <<", name: ">>, string(Name),
     <<", args: rt.args(x, ">>, integer_to_list(Arity), <<"), external: ">>,
     atom_to_list(External), <<", state: {pc: ">>, integer_to_list(Index + 1), <<", y}};">>].

%% Dynamic Module:Function(Args) calls keep their arguments in x0..x(N-1),
%% the module in xN and the function in x(N+1).
apply_args(Arity) ->
    N = integer_to_list(Arity),
    [<<"[rt.read(x, ">>, N, <<"), rt.read(x, ">>, integer_to_list(Arity + 1),
     <<"), rt.args(x, ">>, N, <<").reduceRight((tail, head) => rt.cons(head, tail), rt.nil())]">>].

deallocate(Size) -> [<<"y = rt.deallocate(y, ">>, integer_to_list(Size), <<"); ">>].

init_yregs(Registers, Context, Index) ->
    case [N || {y, N} <- Registers, is_integer(N), N >= 0, N < 1024] of
        Numbers when length(Numbers) =:= length(Registers) ->
            case Numbers =:= lists:usort(Numbers) of
                true ->
                    [<<"rt.initYregs(y, [">>,
                     lists:join(<<", ">>, [integer_to_list(N) || N <- Numbers]),
                     <<"]); ">>, next(Index)];
                false -> unsupported(Context, Index, "invalid y register initialization order")
            end;
        _ -> unsupported(Context, Index, "invalid y register initialization")
    end.

register_operand({x, _} = Register, Context, Index) -> operand(Register, Context, Index);
register_operand({y, _} = Register, Context, Index) -> operand(Register, Context, Index);
register_operand(Other, Context, Index) ->
    unsupported(Context, Index, io_lib:format("unsupported register ~tp", [Other])).

write_register({x, Register}, Value, _, _) when is_integer(Register), Register >= 0, Register < 1024 ->
    [<<"x[">>, integer_to_list(Register), <<"] = ">>, Value, <<"; ">>];
write_register({y, Register}, Value, _, _) when is_integer(Register), Register >= 0, Register < 1024 ->
    [<<"rt.writeY(y, ">>, integer_to_list(Register), <<", ">>, Value, <<"); ">>];
write_register(Other, _, Context, Index) ->
    unsupported(Context, Index, io_lib:format("unsupported register ~tp", [Other])).

operand({x, Register}, _, _) when is_integer(Register), Register >= 0, Register < 1024 ->
    [<<"rt.read(x, ">>, integer_to_list(Register), <<")">>];
operand({y, Register}, _, _) when is_integer(Register), Register >= 0, Register < 1024 ->
    [<<"rt.readY(y, ">>, integer_to_list(Register), <<")">>];
operand({tr, {x, Register}, _Type}, Context, Index)
  when is_integer(Register), Register >= 0, Register < 1024 ->
    operand({x, Register}, Context, Index);
operand({tr, {y, Register}, _Type}, Context, Index)
  when is_integer(Register), Register >= 0, Register < 1024 ->
    operand({y, Register}, Context, Index);
operand({integer, Integer}, _, _) when is_integer(Integer) -> [integer_to_list(Integer), <<"n">>];
operand({atom, Atom}, _, _) when is_atom(Atom) -> [<<"rt.atom(">>, string(Atom), <<")">>];
operand(nil, _, _) -> <<"rt.nil()">>;
operand({literal, Term}, Context, Index) ->
    [<<"(()=>{const s=[];">>, literal_steps([{term, Term}], [], Context, Index),
     <<"return s.pop();})()">>];
operand({float, Float}, _, _) when is_float(Float) ->
    [<<"rt.float(">>, float_to_binary(Float, [short]), <<")">>];
operand(Other, Context, Index) ->
    unsupported(Context, Index, io_lib:format("unsupported operand ~tp", [Other])).

literal_steps([], Steps, _, _) -> lists:reverse(Steps);
literal_steps([{term, []} | Rest], Steps, Context, Index) ->
    literal_steps(Rest, [<<"s.push(rt.nil());">> | Steps], Context, Index);
literal_steps([{term, [Head | Tail]} | Rest], Steps, Context, Index) ->
    literal_steps([{term, Tail}, {term, Head}, cons | Rest], Steps, Context, Index);
literal_steps([{term, Fun} | Rest], Steps, Context, Index) when is_function(Fun) ->
    {module, Module} = erlang:fun_info(Fun, module),
    {name, Name} = erlang:fun_info(Fun, name),
    {arity, Arity} = erlang:fun_info(Fun, arity),
    {env, Environment} = erlang:fun_info(Fun, env),
    Step = [<<"s.push(rt.makeFun(">>, string(Module), <<", ">>, string(Name), <<", ">>,
            integer_to_list(Arity), <<", [">>,
            lists:join(<<", ">>, [literal_inline(E) || E <- Environment]), <<"]));">>],
    literal_steps(Rest, [Step | Steps], Context, Index);
literal_steps([{term, Map} | Rest], Steps, Context, Index) when is_map(Map) ->
    Entries = maps:to_list(Map),
    literal_steps([{map_elements, Entries}, {map, map_size(Map)} | Rest], Steps, Context, Index);
literal_steps([{term, Tuple} | Rest], Steps, Context, Index) when is_tuple(Tuple) ->
    literal_steps([{elements, tuple_to_list(Tuple)}, {tuple, tuple_size(Tuple)} | Rest],
                  Steps, Context, Index);
literal_steps([{term, Integer} | Rest], Steps, Context, Index) when is_integer(Integer) ->
    literal_steps(Rest, [[<<"s.push(">>, integer_to_list(Integer), <<"n);">>] | Steps], Context, Index);
literal_steps([{term, Float} | Rest], Steps, Context, Index) when is_float(Float) ->
    literal_steps(Rest, [[<<"s.push(rt.float(">>, float_to_binary(Float, [short]), <<"));">>] | Steps],
                  Context, Index);
literal_steps([{term, Atom} | Rest], Steps, Context, Index) when is_atom(Atom) ->
    literal_steps(Rest, [[<<"s.push(rt.atom(">>, string(Atom), <<"));">>] | Steps], Context, Index);
literal_steps([{term, Bits} | Rest], Steps, Context, Index) when is_bitstring(Bits) ->
    Size = bit_size(Bits),
    Padding = (8 - Size rem 8) rem 8,
    Bytes = binary_to_list(<<Bits/bitstring, 0:Padding>>),
    Step = [<<"s.push(rt.bitstring([">>,
            lists:join(<<",">>, [integer_to_list(Byte) || Byte <- Bytes]),
            <<"],">>, integer_to_list(Size), <<"));">>],
    literal_steps(Rest, [Step | Steps], Context, Index);
literal_steps([{term, Other} | _], _, Context, Index) ->
    unsupported(Context, Index, io_lib:format("unsupported literal value ~tp", [Other]));
literal_steps([{elements, []} | Rest], Steps, Context, Index) ->
    literal_steps(Rest, Steps, Context, Index);
literal_steps([{elements, [Head | Tail]} | Rest], Steps, Context, Index) ->
    literal_steps([{term, Head}, {elements, Tail} | Rest], Steps, Context, Index);
literal_steps([cons | Rest], Steps, Context, Index) ->
    literal_steps(Rest, [<<"s.push(rt.cons(s.pop(),s.pop()));">> | Steps], Context, Index);
literal_steps([{map_elements, []} | Rest], Steps, Context, Index) ->
    literal_steps(Rest, Steps, Context, Index);
literal_steps([{map_elements, [{Key, Value} | Tail]} | Rest], Steps, Context, Index) ->
    literal_steps([{term, Key}, {term, Value}, {map_elements, Tail} | Rest], Steps, Context, Index);
literal_steps([{map, Size} | Rest], Steps, Context, Index) ->
    Step = [<<"s.push(rt.map((()=>{const entries=[];for(let i=0;i<">>,
            integer_to_list(Size), <<";i++){const value=s.pop(),key=s.pop();entries.unshift([key,value]);}return entries;})()));">>],
    literal_steps(Rest, [Step | Steps], Context, Index);
literal_steps([{tuple, Arity} | Rest], Steps, Context, Index) ->
    literal_steps(Rest, [[<<"s.push(rt.tuple(s.splice(s.length-">>, integer_to_list(Arity),
                           <<",">>, integer_to_list(Arity), <<")));">>] | Steps], Context, Index).

literal_inline(Term) ->
    case Term of
        I when is_integer(I) -> [integer_to_list(I), <<"n">>];
        F when is_float(F) -> [<<"rt.float(">>, float_to_binary(F, [short]), <<")">>];
        A when is_atom(A) -> [<<"rt.atom(">>, string(A), <<")">>];
        [] -> <<"rt.nil()">>;
        L when is_list(L) -> unsupported_literal_inline(L);
        T when is_tuple(T) -> unsupported_literal_inline(T);
        _ -> <<"null">>
    end.
unsupported_literal_inline(Term) ->
    error({unsupported_fun_environment, Term}).

target(Label, Labels, Context, Index) ->
    case maps:find(Label, Labels) of
        {ok, Target} when Label =/= 0 -> integer_to_list(Target);
        _ -> unsupported(Context, Index, io_lib:format("invalid branch label ~tp", [Label]))
    end.

unsupported({Name, Arity}, Index, Reason) ->
    throw({unsupported, io_lib:format("~tp/~B instruction ~tp: ~ts", [Name, Arity, Index, Reason])}).

string(Atom) when is_atom(Atom) ->
    [$", [escape(Codepoint) || Codepoint <- atom_to_list(Atom)], $"].

escape(C) when C >= 16#20, C =< 16#7e, C =/= $", C =/= $\\ -> C;
escape(C) when C =< 16#ffff -> io_lib:format("\\u~4.16.0B", [C]);
escape(C) ->
    Value = C - 16#10000,
    [io_lib:format("\\u~4.16.0B", [16#d800 + (Value bsr 10)]),
     io_lib:format("\\u~4.16.0B", [16#dc00 + (Value band 16#3ff)])].

error_message(Format, Args) -> {error, lists:flatten(io_lib:format(Format, Args))}.
