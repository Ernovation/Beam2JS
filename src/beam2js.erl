-module(beam2js).
-export([main/1, compile_file/2, compile_binary/1]).

-define(MAX_INPUT_SIZE, 32 * 1024 * 1024).

main([Input, Output]) ->
    case compile_file(Input, Output) of
        ok -> ok;
        {error, Reason} ->
            io:format(standard_error, "beam2js: ~ts: ~ts~n", [Input, Reason]),
            erlang:halt(1)
    end;
main(_) ->
    io:format(standard_error, "usage: beam2js INPUT.beam OUTPUT.mjs~n", []),
    erlang:halt(2).

compile_file(Input, Output) ->
    case file:read_file_info(Input) of
        {ok, Info} when element(2, Info) =< ?MAX_INPUT_SIZE ->
            case file:read_file(Input) of
                {ok, Binary} ->
                    case compile_binary(Binary) of
                        {ok, Source} -> write_output(Output, Source);
                        Error -> Error
                    end;
                {error, Reason} -> error_message("cannot read input: ~ts", [file:format_error(Reason)])
            end;
        {ok, _} -> {error, "input exceeds 32 MiB"};
        {error, Reason} -> error_message("cannot stat input: ~ts", [file:format_error(Reason)])
    end.

compile_binary(Binary) when is_binary(Binary), byte_size(Binary) =< ?MAX_INPUT_SIZE ->
    case erlang:system_info(otp_release) of
        "29" ->
            try beam_disasm:file(Binary) of
                {beam_file, Module, Exports, _Attributes, _CompileInfo, Functions} ->
                    try generate(Module, Exports, Functions) of
                        Source -> {ok, iolist_to_binary(Source)}
                    catch
                        throw:{unsupported, Detail} -> {error, lists:flatten(Detail)}
                    end;
                Other -> error_message("cannot disassemble BEAM: ~tp", [Other])
            catch
                Class:Reason -> error_message("cannot disassemble BEAM (~p): ~tp", [Class, Reason])
            end;
        Release -> error_message("unsupported host OTP release ~s (requires OTP 29)", [Release])
    end;
compile_binary(Binary) when is_binary(Binary) ->
    {error, "input exceeds 32 MiB"}.

write_output(Output, Source) ->
    Temp = Output ++ "." ++ integer_to_list(erlang:unique_integer([positive, monotonic])) ++ ".tmp",
    case file:open(Temp, [write, binary, exclusive]) of
        {ok, File} ->
            Result = case file:write(File, Source) of
                ok -> file:close(File);
                {error, _} = WriteError ->
                    _ = file:close(File),
                    WriteError
            end,
            case Result of
                ok ->
                    case file:rename(Temp, Output) of
                        ok -> ok;
                        {error, RenameReason} ->
                            _ = file:delete(Temp),
                            error_message("cannot replace output: ~ts", [file:format_error(RenameReason)])
                    end;
                {error, WriteReason} ->
                    _ = file:delete(Temp),
                    error_message("cannot write output: ~ts", [file:format_error(WriteReason)])
            end;
        {error, OpenReason} ->
            error_message("cannot create temporary output: ~ts", [file:format_error(OpenReason)])
    end.

generate(Module, Exports, Functions) ->
    FunctionKeys = [{Name, Arity} || {function, Name, Arity, _, _} <- Functions],
    [<<"// Generated by beam2js; runtime ABI 15.\nexport function register(runtime) {\n">>,
     <<"  runtime.registerModule(15, ">>, string(Module), <<", [\n">>,
     lists:join(<<",\n">>, [function(Module, F, Exports, FunctionKeys) || F <- Functions]),
     <<"\n  ]);\n}\n">>].

function(Module, {function, Name, Arity, Entry, Instructions}, Exports, FunctionKeys) ->
    Context = {Name, Arity},
    Labels = maps:from_list([{Label, Index} ||
                             {{label, Label}, Index} <- indexed(Instructions)]),
    case maps:find(Entry, Labels) of
        {ok, EntryIndex} ->
            Exported = lists:member({Name, Arity, Entry}, Exports),
            [<<"    {name: ">>, string(Name), <<", arity: ">>, integer_to_list(Arity),
             <<", exported: ">>, atom_to_list(Exported),
             <<", run: (rt, x, state) => {\n      let pc = state ? state.pc : ">>,
             integer_to_list(EntryIndex),
             <<";\n      let y = state ? state.y : null;\n      while (true) {\n        switch (pc) {\n">>,
             [instruction(I, Index, Labels, Module, Context, FunctionKeys) ||
                 {I, Index} <- indexed(Instructions)],
             <<"          default: throw new Error('invalid BEAM program counter');\n">>,
             <<"        }\n      }\n    }}">>];
        error -> unsupported(Context, Entry, "missing entry label")
    end.

indexed(List) -> lists:zip(List, lists:seq(0, length(List) - 1)).

instruction(Instruction, Index, Labels, Module, Context, FunctionKeys) ->
    Body = case Instruction of
        {label, _} -> next(Index);
        {line, _} -> next(Index);
        {func_info, {atom, Module}, {atom, Name}, Arity} when Context =:= {Name, Arity} ->
            <<"throw new Error('Erlang function_clause');">>;
        {move, Source, {x, Dest}} when is_integer(Dest), Dest >= 0, Dest < 1024 ->
            [<<"x[">>, integer_to_list(Dest), <<"] = ">>, operand(Source, Context, Index), <<"; ">>, next(Index)];
        {move, Source, {y, Dest}} when is_integer(Dest), Dest >= 0, Dest < 1024 ->
            [<<"rt.writeY(y, ">>, integer_to_list(Dest), <<", ">>, operand(Source, Context, Index),
             <<"); ">>, next(Index)];
        {swap, Left, Right} ->
            [<<"{ const left = ">>, register_operand(Left, Context, Index),
             <<"; const right = ">>, register_operand(Right, Context, Index), <<"; ">>,
             write_register(Left, <<"right">>, Context, Index),
             write_register(Right, <<"left">>, Context, Index), <<"} ">>, next(Index)];
        {allocate, Size, Live}
          when is_integer(Size), Size >= 0, Size =< 1024,
               is_integer(Live), Live >= 0, Live =< 1024 ->
            [<<"y = rt.allocate(y, ">>, integer_to_list(Size), <<"); ">>, next(Index)];
        {allocate_heap, Size, Words, Live}
          when is_integer(Size), Size >= 0, Size =< 1024, is_integer(Words), Words >= 0,
               is_integer(Live), Live >= 0, Live =< 1024 ->
            [<<"y = rt.allocate(y, ">>, integer_to_list(Size), <<"); ">>, next(Index)];
        {deallocate, Size} when is_integer(Size), Size >= 0, Size =< 1024 ->
            [deallocate(Size), next(Index)];
        {init_yregs, {list, Registers}} when is_list(Registers), Registers =/= [] ->
            init_yregs(Registers, Context, Index);
        {trim, Count, Remaining}
          when is_integer(Count), Count >= 0, Count =< 1024,
               is_integer(Remaining), Remaining >= 0, Remaining =< 1024 ->
            [<<"y = rt.trim(y, ">>, integer_to_list(Count), <<", ">>,
             integer_to_list(Remaining), <<"); ">>, next(Index)];
        {test, Op, {f, Target}, [Left, Right]}
          when Op =:= is_eq_exact; Op =:= is_ne_exact; Op =:= is_eq;
               Op =:= is_ne; Op =:= is_lt; Op =:= is_ge ->
            Condition = comparison(Op, operand(Left, Context, Index), operand(Right, Context, Index)),
            branch(Condition, Target, Index, Labels, Context);
        {test, Op, {f, Target}, [Source]}
          when Op =:= is_integer; Op =:= is_number; Op =:= is_atom;
               Op =:= is_boolean; Op =:= is_float; Op =:= is_nil;
               Op =:= is_list; Op =:= is_nonempty_list; Op =:= is_tuple;
               Op =:= is_binary; Op =:= is_bitstr ->
            Condition = type_test(Op, Source, Context, Index),
            branch(Condition, Target, Index, Labels, Context);
        {test, test_arity, {f, Target}, [Source, Arity]}
          when is_integer(Arity), Arity >= 0, Arity =< 9007199254740991 ->
            Condition = [<<"rt.tupleSize(">>, operand(Source, Context, Index), <<") === ">>,
                         integer_to_list(Arity)],
            branch(Condition, Target, Index, Labels, Context);
        {test, is_tagged_tuple, {f, Target}, [Source, Arity, {atom, Tag}]}
          when is_integer(Arity), Arity > 0, Arity =< 9007199254740991, is_atom(Tag) ->
            Condition = [<<"(value => rt.isType('is_tuple', value) && rt.tupleSize(value) === ">>,
                         integer_to_list(Arity), <<" && rt.equalExact(rt.tupleElement(value, 1), rt.atom(">>,
                         string(Tag), <<")))(">>, operand(Source, Context, Index), <<")">>],
            branch(Condition, Target, Index, Labels, Context);
        {bif, Op, {f, 0}, [Source], {x, Dest}}
          when is_integer(Dest), Dest >= 0, Dest < 1024,
               (Op =:= is_integer orelse Op =:= is_number orelse Op =:= is_atom orelse
                Op =:= is_boolean orelse Op =:= is_float orelse Op =:= is_list orelse
                Op =:= is_tuple orelse Op =:= is_binary orelse Op =:= is_bitstring) ->
            [<<"x[">>, integer_to_list(Dest), <<"] = rt.atom(">>,
             type_test(Op, Source, Context, Index),
             <<" ? 'true' : 'false'); ">>, next(Index)];
        {bif, Op, {f, Target}, [Source], {x, Dest}}
          when (Op =:= hd orelse Op =:= tl orelse Op =:= tuple_size),
               is_integer(Dest), Dest >= 0, Dest < 1024 ->
            guard_bif(Op, [Source], Dest, Target, Index, Labels, Context);
        {bif, element, {f, Target}, [Position, Source], {x, Dest}}
          when is_integer(Dest), Dest >= 0, Dest < 1024 ->
            guard_bif(element, [Position, Source], Dest, Target, Index, Labels, Context);
        {gc_bif, Op, {f, Target}, Live, [Source], {x, Dest}}
          when (Op =:= 'bnot' orelse Op =:= length orelse Op =:= '-' orelse Op =:= abs orelse
                Op =:= trunc orelse Op =:= round orelse Op =:= floor orelse Op =:= ceil orelse
                Op =:= float orelse Op =:= bit_size orelse Op =:= byte_size),
               is_integer(Live), Live >= 0, Live =< 1024,
               is_integer(Dest), Dest >= 0, Dest < 1024 ->
            guard_bif(Op, [Source], Dest, Target, Index, Labels, Context);
        {gc_bif, Op, {f, Target}, Live, [Left, Right], {x, Dest}}
          when (Op =:= 'band' orelse Op =:= 'bor' orelse Op =:= 'bxor' orelse
                Op =:= 'div' orelse Op =:= 'rem' orelse Op =:= '+' orelse
                Op =:= '-' orelse Op =:= '*' orelse Op =:= '/' orelse Op =:= binary_part),
               is_integer(Live), Live >= 0, Live =< 1024,
               is_integer(Dest), Dest >= 0, Dest < 1024 ->
            guard_bif(Op, [Left, Right], Dest, Target, Index, Labels, Context);
        {gc_bif, binary_part, {f, Target}, Live, [Source, Position, Length], {x, Dest}}
          when is_integer(Live), Live >= 0, Live =< 1024,
               is_integer(Dest), Dest >= 0, Dest < 1024 ->
            guard_bif(binary_part, [Source, Position, Length], Dest, Target, Index, Labels, Context);
        {test_heap, Words, Live}
          when is_integer(Words), Words >= 0, is_integer(Live), Live >= 0, Live =< 1024 ->
            next(Index);
        {put_list, Head, Tail, {x, Dest}} when is_integer(Dest), Dest >= 0, Dest < 1024 ->
            [<<"x[">>, integer_to_list(Dest), <<"] = rt.cons(">>,
             operand(Head, Context, Index), <<", ">>, operand(Tail, Context, Index),
             <<"); ">>, next(Index)];
        {get_hd, Source, {x, Dest}} when is_integer(Dest), Dest >= 0, Dest < 1024 ->
            [<<"x[">>, integer_to_list(Dest), <<"] = rt.listHead(">>,
             operand(Source, Context, Index), <<"); ">>, next(Index)];
        {get_tl, Source, {x, Dest}} when is_integer(Dest), Dest >= 0, Dest < 1024 ->
            [<<"x[">>, integer_to_list(Dest), <<"] = rt.listTail(">>,
             operand(Source, Context, Index), <<"); ">>, next(Index)];
        {get_list, Source, {x, Head}, {x, Tail}}
          when is_integer(Head), Head >= 0, Head < 1024, is_integer(Tail), Tail >= 0, Tail < 1024,
               Head =/= Tail ->
            [<<"{ const list = ">>, operand(Source, Context, Index), <<"; x[">>,
             integer_to_list(Head), <<"] = rt.listHead(list); x[">>, integer_to_list(Tail),
             <<"] = rt.listTail(list); } ">>, next(Index)];
        {put_tuple2, {x, Dest}, {list, Elements}}
          when is_integer(Dest), Dest >= 0, Dest < 1024, is_list(Elements) ->
            [<<"x[">>, integer_to_list(Dest), <<"] = rt.tuple([">>,
             lists:join(<<", ">>, [operand(E, Context, Index) || E <- Elements]),
             <<"]); ">>, next(Index)];
        {get_tuple_element, Source, Element, {x, Dest}}
          when is_integer(Element), Element >= 0, Element < 9007199254740991,
               is_integer(Dest), Dest >= 0, Dest < 1024 ->
            [<<"x[">>, integer_to_list(Dest), <<"] = rt.tupleElement(">>,
             operand(Source, Context, Index), <<", ">>, integer_to_list(Element + 1),
             <<"); ">>, next(Index)];
        {select_val, Source, {f, Fail}, {list, Choices}} when is_list(Choices) ->
            selection(value, Source, Fail, Choices, Labels, Context, Index);
        {select_tuple_arity, Source, {f, Fail}, {list, Choices}} when is_list(Choices) ->
            selection(arity, Source, Fail, Choices, Labels, Context, Index);
        {jump, {f, Target}} ->
            [<<"pc = ">>, target(Target, Labels, Context, Index), <<"; break;">>];
        {call, Arity, {Module, Name, Arity}} when is_integer(Arity), Arity >= 0, Arity =< 255 ->
            case lists:member({Name, Arity}, FunctionKeys) of
                true -> call(Module, Name, Arity, false, Index);
                false -> unsupported(Context, Index, "unknown local function")
            end;
        {call_ext, Arity, {extfunc, ExtModule, Name, Arity}}
          when is_integer(Arity), Arity >= 0, Arity =< 255 ->
            call(ExtModule, Name, Arity, true, Index);
        {call_last, Arity, {Module, Name, Arity}, Size}
          when is_integer(Arity), Arity >= 0, Arity =< 255,
               is_integer(Size), Size >= 0, Size =< 1024 ->
            case lists:member({Name, Arity}, FunctionKeys) of
                true -> [deallocate(Size), tail_call(Module, Name, Arity, false)];
                false -> unsupported(Context, Index, "unknown local function")
            end;
        {call_ext_last, Arity, {extfunc, ExtModule, Name, Arity}, Size}
          when is_integer(Arity), Arity >= 0, Arity =< 255,
               is_integer(Size), Size >= 0, Size =< 1024 ->
            [deallocate(Size), tail_call(ExtModule, Name, Arity, true)];
        {call_only, Arity, {Module, Name, Arity}} when is_integer(Arity), Arity >= 0, Arity =< 255 ->
            case lists:member({Name, Arity}, FunctionKeys) of
                true -> tail_call(Module, Name, Arity, false);
                false -> unsupported(Context, Index, "unknown local function")
            end;
        {call_ext_only, Arity, {extfunc, ExtModule, Name, Arity}}
          when is_integer(Arity), Arity >= 0, Arity =< 255 ->
            tail_call(ExtModule, Name, Arity, true);
        return -> <<"if (y !== null) throw new Error('return with allocated stack frame'); return {type: 'return', value: rt.read(x, 0)};">>;
        _ -> unsupported(Context, Index, io_lib:format("unsupported instruction ~tp", [Instruction]))
    end,
    [<<"          case ">>, integer_to_list(Index), <<": ">>, Body, <<"\n">>].

next(Index) -> [<<"pc = ">>, integer_to_list(Index + 1), <<"; break;">>].

type_test(Op, Source, Context, Index) ->
    [<<"rt.isType(">>, string(Op), <<", ">>, operand(Source, Context, Index), <<")">>].

guard_bif(Op, Sources, Dest, Target, Index, Labels, Context) ->
    Values = [operand(Source, Context, Index) || Source <- Sources],
    {Declarations, Condition, Result} = case {Op, Values} of
        {hd, [Value]} ->
            {[<<"const value = ">>, Value, <<"; ">>],
             <<"rt.isType('is_nonempty_list', value)">>, <<"rt.listHead(value)">>};
        {tl, [Value]} ->
            {[<<"const value = ">>, Value, <<"; ">>],
             <<"rt.isType('is_nonempty_list', value)">>, <<"rt.listTail(value)">>};
        {tuple_size, [Value]} ->
            {[<<"const value = ">>, Value, <<"; ">>],
             <<"rt.isType('is_tuple', value)">>, <<"BigInt(rt.tupleSize(value))">>};
        {element, [Position, Value]} ->
            {[<<"const position = ">>, Position, <<"; const value = ">>, Value, <<"; ">>],
             <<"typeof position === 'bigint' && position >= 1n && rt.isType('is_tuple', value) && position <= BigInt(rt.tupleSize(value))">>,
             <<"rt.tupleElement(value, Number(position))">>};
        {'bnot', [Value]} ->
            {[<<"const value = ">>, Value, <<"; ">>],
             <<"typeof value === 'bigint'">>, <<"~value">>};
        {length, [Value]} ->
            {[<<"let value = ">>, Value,
              <<"; let length = 0n; while (rt.isType('is_nonempty_list', value)) { ">>,
              <<"value = rt.listTail(value); length += 1n; } ">>],
             <<"rt.isType('is_nil', value)">>, <<"length">>};
        {SizeOp, [Value]} when SizeOp =:= bit_size; SizeOp =:= byte_size ->
            Size = case SizeOp of
                bit_size -> <<"rt.bitstringSize(value)">>;
                byte_size -> <<"Math.ceil(rt.bitstringSize(value) / 8)">>
            end,
            {[<<"const value = ">>, Value, <<"; ">>],
             <<"rt.isType('is_bitstr', value)">>, [<<"BigInt(">>, Size, <<")">>]};
        {binary_part, [Value, Position, Length]} ->
            {[<<"const result = rt.guardBinaryPart(">>, Value, <<", ">>, Position, <<", ">>,
              Length, <<"); ">>], <<"result !== null">>, <<"result">>};
        {binary_part, [Value, Range]} ->
            {[<<"const value = ">>, Value, <<"; const range = ">>, Range,
              <<"; const result = rt.isType('is_tuple', range) && rt.tupleSize(range) === 2 ? ">>,
              <<"rt.guardBinaryPart(value, rt.tupleElement(range, 1), rt.tupleElement(range, 2)) : null; ">>],
             <<"result !== null">>, <<"result">>};
        {'-', [Value]} ->
            {[<<"const result = rt.guardArithmetic('neg', ">>, Value, <<"); ">>],
             <<"result !== null">>, <<"result">>};
        {Unary, [Value]} when Unary =:= abs; Unary =:= trunc; Unary =:= round;
                              Unary =:= floor; Unary =:= ceil; Unary =:= float ->
            {[<<"const result = rt.guardArithmetic(">>, string(Unary), <<", ">>, Value, <<"); ">>],
             <<"result !== null">>, <<"result">>};
        {Arithmetic, [Left, Right]}
          when Arithmetic =:= '+'; Arithmetic =:= '-'; Arithmetic =:= '*'; Arithmetic =:= '/' ->
            {[<<"const result = rt.guardArithmetic(">>, string(Arithmetic), <<", ">>, Left,
              <<", ">>, Right, <<"); ">>],
             <<"result !== null">>, <<"result">>};
        {IntegerOp, [Left, Right]}
          when IntegerOp =:= 'band'; IntegerOp =:= 'bor'; IntegerOp =:= 'bxor';
               IntegerOp =:= 'div'; IntegerOp =:= 'rem' ->
            {Operator, Nonzero} = case IntegerOp of
                'band' -> {<<" & ">>, <<>>};
                'bor' -> {<<" | ">>, <<>>};
                'bxor' -> {<<" ^ ">>, <<>>};
                'div' -> {<<" / ">>, <<" && right !== 0n">>};
                'rem' -> {<<" % ">>, <<" && right !== 0n">>}
            end,
            {[<<"const left = ">>, Left, <<"; const right = ">>, Right, <<"; ">>],
             [<<"typeof left === 'bigint' && typeof right === 'bigint'">>, Nonzero],
             [<<"left">>, Operator, <<"right">>]}
    end,
    [<<"{ ">>, Declarations, <<"if (">>, Condition, <<") { x[">>, integer_to_list(Dest),
     <<"] = ">>, Result, <<"; pc = ">>, integer_to_list(Index + 1), <<"; } else { pc = ">>,
     target(Target, Labels, Context, Index), <<"; } break; }">>].

selection(Kind, Source, Fail, Choices, Labels, Context, Index) ->
    Value = operand(Source, Context, Index),
    Read = case Kind of
        value -> Value;
        arity -> [<<"rt.tupleSize(">>, Value, <<")">>]
    end,
    Cases = selection_cases(Kind, Choices, undefined, #{}, Labels, Context, Index),
    [<<"{ const value = ">>, Read, <<"; ">>, Cases, <<"pc = ">>,
     target(Fail, Labels, Context, Index), <<"; break; }">>].

selection_cases(_, [], _, _, _, _, _) -> [];
selection_cases(Kind, [Choice, {f, Label} | Rest], Expected, Seen, Labels, Context, Index) ->
    {ChoiceKind, Key} = selection_choice(Kind, Choice, Context, Index),
    case (Expected =:= undefined orelse Expected =:= ChoiceKind) andalso
         not maps:is_key(Key, Seen) of
        true -> ok;
        false -> unsupported(Context, Index, "mixed or duplicate selection choices")
    end,
    Condition = case Kind of
        value -> [<<"rt.equalExact(value, ">>, operand(Choice, Context, Index), <<")">>];
        arity -> [<<"value === ">>, integer_to_list(Key)]
    end,
    [<<"if (">>, Condition, <<") { pc = ">>, target(Label, Labels, Context, Index),
     <<"; break; } ">>,
     selection_cases(Kind, Rest, ChoiceKind, Seen#{Key => true}, Labels, Context, Index)];
selection_cases(_, _, _, _, _, Context, Index) ->
    unsupported(Context, Index, "invalid selection choice list").

selection_choice(arity, Key, _, _) when is_integer(Key), Key >= 0, Key =< 9007199254740991 ->
    {arity, Key};
selection_choice(value, {atom, Key}, _, _) when is_atom(Key) -> {atom, Key};
selection_choice(value, {integer, Key}, _, _) when is_integer(Key) -> {integer, Key};
selection_choice(value, {float, Key}, _, _) when is_float(Key) -> {float, Key};
selection_choice(value, {literal, Key}, _, _) when is_atom(Key) -> {atom, Key};
selection_choice(value, {literal, Key}, _, _) when is_integer(Key) -> {integer, Key};
selection_choice(value, {literal, Key}, _, _) when is_float(Key) -> {float, Key};
selection_choice(_, _, Context, Index) -> unsupported(Context, Index, "invalid selection choice").

comparison(Op, Left, Right) ->
    {Prefix, Function, Suffix} = case Op of
        is_eq_exact -> {<<>>, <<"equalExact">>, <<>>};
        is_ne_exact -> {<<"!">>, <<"equalExact">>, <<>>};
        is_eq -> {<<>>, <<"equalNumeric">>, <<>>};
        is_ne -> {<<"!">>, <<"equalNumeric">>, <<>>};
        is_lt -> {<<>>, <<"compare">>, <<" < 0">>};
        is_ge -> {<<>>, <<"compare">>, <<" >= 0">>}
    end,
    [Prefix, <<"rt.">>, Function, <<"(">>, Left, <<", ">>, Right, <<")">>, Suffix].

branch(Condition, Target, Index, Labels, Context) ->
    [<<"pc = ">>, Condition, <<" ? ">>, integer_to_list(Index + 1), <<" : ">>,
     target(Target, Labels, Context, Index), <<"; break;">>].

tail_call(Module, Name, Arity, External) ->
    [<<"return {type: 'tail', module: ">>, string(Module), <<", name: ">>, string(Name),
     <<", args: rt.args(x, ">>, integer_to_list(Arity), <<"), external: ">>,
     atom_to_list(External), <<"};">>].

call(Module, Name, Arity, External, Index) ->
    [<<"if (y === null) throw new Error('call without allocated stack frame'); ">>,
     <<"return {type: 'call', module: ">>, string(Module), <<", name: ">>, string(Name),
     <<", args: rt.args(x, ">>, integer_to_list(Arity), <<"), external: ">>,
     atom_to_list(External), <<", state: {pc: ">>, integer_to_list(Index + 1), <<", y}};">>].

deallocate(Size) -> [<<"y = rt.deallocate(y, ">>, integer_to_list(Size), <<"); ">>].

init_yregs(Registers, Context, Index) ->
    case [N || {y, N} <- Registers, is_integer(N), N >= 0, N < 1024] of
        Numbers when length(Numbers) =:= length(Registers) ->
            case Numbers =:= lists:usort(Numbers) of
                true ->
                    [<<"rt.initYregs(y, [">>,
                     lists:join(<<", ">>, [integer_to_list(N) || N <- Numbers]),
                     <<"]); ">>, next(Index)];
                false -> unsupported(Context, Index, "invalid y register initialization order")
            end;
        _ -> unsupported(Context, Index, "invalid y register initialization")
    end.

register_operand({x, _} = Register, Context, Index) -> operand(Register, Context, Index);
register_operand({y, _} = Register, Context, Index) -> operand(Register, Context, Index);
register_operand(Other, Context, Index) ->
    unsupported(Context, Index, io_lib:format("unsupported register ~tp", [Other])).

write_register({x, Register}, Value, _, _) when is_integer(Register), Register >= 0, Register < 1024 ->
    [<<"x[">>, integer_to_list(Register), <<"] = ">>, Value, <<"; ">>];
write_register({y, Register}, Value, _, _) when is_integer(Register), Register >= 0, Register < 1024 ->
    [<<"rt.writeY(y, ">>, integer_to_list(Register), <<", ">>, Value, <<"); ">>];
write_register(Other, _, Context, Index) ->
    unsupported(Context, Index, io_lib:format("unsupported register ~tp", [Other])).

operand({x, Register}, _, _) when is_integer(Register), Register >= 0, Register < 1024 ->
    [<<"rt.read(x, ">>, integer_to_list(Register), <<")">>];
operand({y, Register}, _, _) when is_integer(Register), Register >= 0, Register < 1024 ->
    [<<"rt.readY(y, ">>, integer_to_list(Register), <<")">>];
operand({tr, {x, Register}, _Type}, Context, Index)
  when is_integer(Register), Register >= 0, Register < 1024 ->
    operand({x, Register}, Context, Index);
operand({integer, Integer}, _, _) when is_integer(Integer) -> [integer_to_list(Integer), <<"n">>];
operand({atom, Atom}, _, _) when is_atom(Atom) -> [<<"rt.atom(">>, string(Atom), <<")">>];
operand(nil, _, _) -> <<"rt.nil()">>;
operand({literal, Term}, Context, Index) ->
    [<<"(()=>{const s=[];">>, literal_steps([{term, Term}], [], Context, Index),
     <<"return s.pop();})()">>];
operand({float, Float}, _, _) when is_float(Float) ->
    [<<"rt.float(">>, float_to_binary(Float, [short]), <<")">>];
operand(Other, Context, Index) ->
    unsupported(Context, Index, io_lib:format("unsupported operand ~tp", [Other])).

literal_steps([], Steps, _, _) -> lists:reverse(Steps);
literal_steps([{term, []} | Rest], Steps, Context, Index) ->
    literal_steps(Rest, [<<"s.push(rt.nil());">> | Steps], Context, Index);
literal_steps([{term, [Head | Tail]} | Rest], Steps, Context, Index) ->
    literal_steps([{term, Tail}, {term, Head}, cons | Rest], Steps, Context, Index);
literal_steps([{term, Tuple} | Rest], Steps, Context, Index) when is_tuple(Tuple) ->
    literal_steps([{elements, tuple_to_list(Tuple)}, {tuple, tuple_size(Tuple)} | Rest],
                  Steps, Context, Index);
literal_steps([{term, Integer} | Rest], Steps, Context, Index) when is_integer(Integer) ->
    literal_steps(Rest, [[<<"s.push(">>, integer_to_list(Integer), <<"n);">>] | Steps], Context, Index);
literal_steps([{term, Float} | Rest], Steps, Context, Index) when is_float(Float) ->
    literal_steps(Rest, [[<<"s.push(rt.float(">>, float_to_binary(Float, [short]), <<"));">>] | Steps],
                  Context, Index);
literal_steps([{term, Atom} | Rest], Steps, Context, Index) when is_atom(Atom) ->
    literal_steps(Rest, [[<<"s.push(rt.atom(">>, string(Atom), <<"));">>] | Steps], Context, Index);
literal_steps([{term, Bits} | Rest], Steps, Context, Index) when is_bitstring(Bits) ->
    Size = bit_size(Bits),
    Padding = (8 - Size rem 8) rem 8,
    Bytes = binary_to_list(<<Bits/bitstring, 0:Padding>>),
    Step = [<<"s.push(rt.bitstring([">>,
            lists:join(<<",">>, [integer_to_list(Byte) || Byte <- Bytes]),
            <<"],">>, integer_to_list(Size), <<"));">>],
    literal_steps(Rest, [Step | Steps], Context, Index);
literal_steps([{term, Other} | _], _, Context, Index) ->
    unsupported(Context, Index, io_lib:format("unsupported literal value ~tp", [Other]));
literal_steps([{elements, []} | Rest], Steps, Context, Index) ->
    literal_steps(Rest, Steps, Context, Index);
literal_steps([{elements, [Head | Tail]} | Rest], Steps, Context, Index) ->
    literal_steps([{term, Head}, {elements, Tail} | Rest], Steps, Context, Index);
literal_steps([cons | Rest], Steps, Context, Index) ->
    literal_steps(Rest, [<<"s.push(rt.cons(s.pop(),s.pop()));">> | Steps], Context, Index);
literal_steps([{tuple, Arity} | Rest], Steps, Context, Index) ->
    literal_steps(Rest, [[<<"s.push(rt.tuple(s.splice(s.length-">>, integer_to_list(Arity),
                           <<",">>, integer_to_list(Arity), <<")));">>] | Steps], Context, Index).

target(Label, Labels, Context, Index) ->
    case maps:find(Label, Labels) of
        {ok, Target} when Label =/= 0 -> integer_to_list(Target);
        _ -> unsupported(Context, Index, io_lib:format("invalid branch label ~tp", [Label]))
    end.

unsupported({Name, Arity}, Index, Reason) ->
    throw({unsupported, io_lib:format("~tp/~B instruction ~tp: ~ts", [Name, Arity, Index, Reason])}).

string(Atom) when is_atom(Atom) ->
    [$", [escape(Codepoint) || Codepoint <- atom_to_list(Atom)], $"].

escape(C) when C >= 16#20, C =< 16#7e, C =/= $", C =/= $\\ -> C;
escape(C) when C =< 16#ffff -> io_lib:format("\\u~4.16.0B", [C]);
escape(C) ->
    Value = C - 16#10000,
    [io_lib:format("\\u~4.16.0B", [16#d800 + (Value bsr 10)]),
     io_lib:format("\\u~4.16.0B", [16#dc00 + (Value band 16#3ff)])].

error_message(Format, Args) -> {error, lists:flatten(io_lib:format(Format, Args))}.
