%% Exercises the stdlib lists module compiled from OTP's own lists.beam.
%% test/lists-cases.mjs runs every scenario under OTP and under Beam2JS.
-module(lists_cases).
-export([scenarios/0, run/1]).
-compile(nowarn_deprecated_function).

scenarios() ->
    [S || {S, _} <- cases()].

run(Scenario) ->
    {Scenario, Fun} = lists:keyfind(Scenario, 1, cases()),
    try Fun()
    catch Class:Reason -> {Class, Reason}
    end.

cases() ->
    L = [3, 1, 4, 1, 5, 9, 2, 6],
    T = [{b, 2}, {a, 1}, {c, 3}, {a, 0}],
    Even = fun(X) -> X rem 2 =:= 0 end,
    [{all, fun() -> {lists:all(Even, [2, 4]), lists:all(Even, L), lists:all(Even, [])} end},
     {any, fun() -> {lists:any(Even, L), lists:any(Even, [1, 3]), lists:any(Even, [])} end},
     {append, fun() -> {lists:append([[1], [2, 3], [], [4]]), lists:append([a], [b])} end},
     {concat, fun() -> lists:concat([foo, "_", 12, bar]) end},
     {delete, fun() -> {lists:delete(1, L), lists:delete(x, L)} end},
     {droplast, fun() -> lists:droplast(L) end},
     {droplast_empty, fun() -> lists:droplast([]) end},
     {dropwhile, fun() -> lists:dropwhile(fun(X) -> X < 4 end, L) end},
     {duplicate, fun() -> {lists:duplicate(3, x), lists:duplicate(0, x)} end},
     {enumerate, fun() -> {lists:enumerate([a, b]), lists:enumerate(0, [a, b]),
                           lists:enumerate(10, -2, [a, b, c])} end},
     {filter, fun() -> lists:filter(Even, L) end},
     {filtermap, fun() -> lists:filtermap(fun(X) when X > 4 -> {true, X * 10};
                                             (X) -> X =:= 1 end, L) end},
     {flatlength, fun() -> lists:flatlength([1, [2, [3, 4]], [], 5]) end},
     {flatmap, fun() -> lists:flatmap(fun(X) -> [X, X] end, [1, 2]) end},
     {flatten, fun() -> {lists:flatten([1, [2, [3, [4]]], []]), lists:flatten([[a]], [b])} end},
     {foldl, fun() -> lists:foldl(fun(X, Acc) -> [X | Acc] end, [], L) end},
     {foldr, fun() -> lists:foldr(fun(X, Acc) -> [X | Acc] end, [], L) end},
     {foreach, fun() -> lists:foreach(fun(X) -> put(X, X) end, [k1, k2]), {get(k1), get(k2)} end},
     {join, fun() -> {lists:join(x, [a, b, c]), lists:join(x, [])} end},
     {keydelete, fun() -> lists:keydelete(a, 1, T) end},
     {keyfind, fun() -> {lists:keyfind(c, 1, T), lists:keyfind(z, 1, T), lists:keyfind(1, 2, T),
                         lists:keyfind(1.0, 2, T)} end},
     {keymap, fun() -> lists:keymap(fun(X) -> X * 100 end, 2, T) end},
     {keymember, fun() -> {lists:keymember(a, 1, T), lists:keymember(z, 1, T)} end},
     {keymerge, fun() -> lists:keymerge(1, [{a, 1}, {c, 3}], [{b, 2}, {d, 4}]) end},
     {keyreplace, fun() -> lists:keyreplace(a, 1, T, {a, new}) end},
     {keysearch, fun() -> {lists:keysearch(b, 1, T), lists:keysearch(z, 1, T)} end},
     {keysort, fun() -> {lists:keysort(1, T), lists:keysort(2, T)} end},
     {keystore, fun() -> {lists:keystore(a, 1, T, {a, x}), lists:keystore(z, 1, T, {z, 9})} end},
     {keytake, fun() -> {lists:keytake(c, 1, T), lists:keytake(z, 1, T)} end},
     {last, fun() -> lists:last(L) end},
     {map, fun() -> lists:map(fun(X) -> X * X end, L) end},
     {mapfoldl, fun() -> lists:mapfoldl(fun(X, S) -> {X * 2, S + X} end, 0, L) end},
     {mapfoldr, fun() -> lists:mapfoldr(fun(X, S) -> {X * 2, [X | S]} end, [], L) end},
     {max_min, fun() -> {lists:max(L), lists:min(L), lists:max([a, 1, "s", {t}]),
                         lists:min([a, 1, 0.5])} end},
     {member, fun() -> {lists:member(9, L), lists:member(7, L), lists:member(1.0, L)} end},
     {merge, fun() -> {lists:merge([[1, 4], [2, 3], [0]]), lists:merge([1, 3], [2, 4]),
                       lists:merge(fun(A, B) -> A >= B end, [4, 1], [3, 2])} end},
     {merge3, fun() -> {lists:merge3([1, 4], [2, 5], [3, 6]), lists:rmerge3([4, 1], [5, 2], [6, 3])} end},
     {rmerge, fun() -> {lists:rmerge([3, 1], [4, 2]), lists:rmerge(fun(A, B) -> A =< B end, [1, 3], [2, 4])} end},
     {nth, fun() -> {lists:nth(1, L), lists:nth(8, L)} end},
     {nth_bad, fun() -> lists:nth(9, L) end},
     {nthtail, fun() -> {lists:nthtail(5, L), lists:nthtail(0, [a])} end},
     {partition, fun() -> lists:partition(Even, L) end},
     {prefix_suffix, fun() -> {lists:prefix([3, 1], L), lists:prefix([1], L),
                               lists:suffix([2, 6], L), lists:suffix([6, 2], L)} end},
     {reverse, fun() -> {lists:reverse(L), lists:reverse([]), lists:reverse([1, 2], [3]),
                         lists:reverse([a], b)} end},
     {reverse_bad, fun() -> lists:reverse(not_a_list, []) end},
     {search, fun() -> {lists:search(fun(X) -> X > 4 end, L), lists:search(fun(X) -> X > 9 end, L)} end},
     {seq, fun() -> {lists:seq(1, 5), lists:seq(1, 0), lists:seq(1, 10, 3), lists:seq(10, 1, -4),
                     lists:seq(5, 5, 0)} end},
     {seq_bad, fun() -> lists:seq(3, 1) end},
     {sort, fun() -> {lists:sort(L), lists:sort([b, 2, "x", {}, 1.5, a, [], 2.0]),
                      lists:sort(fun(A, B) -> A >= B end, L),
                      lists:sort(lists:reverse(lists:seq(1, 40)) ++ lists:seq(1, 40))} end},
     {split, fun() -> {lists:split(3, L), lists:splitwith(fun(X) -> X < 4 end, L)} end},
     {split_bad, fun() -> lists:split(20, L) end},
     {sublist, fun() -> {lists:sublist(L, 3), lists:sublist(L, 2, 3), lists:sublist(L, 20)} end},
     {subtract, fun() -> {lists:subtract(L, [1, 9, 7]), L -- [1, 1, 1], [a, b] ++ [c]} end},
     {sum, fun() -> {lists:sum(L), lists:sum([]), lists:sum([1, 2.5])} end},
     {takewhile, fun() -> lists:takewhile(fun(X) -> X < 5 end, L) end},
     {ukeymerge, fun() -> {lists:ukeymerge(1, [{a, 1}, {b, 2}], [{a, 3}, {c, 4}]),
                           lists:rukeymerge(1, [{c, 4}, {a, 3}], [{b, 2}, {a, 1}]),
                           lists:rkeymerge(1, [{c, 4}, {a, 3}], [{b, 2}])} end},
     {ukeysort, fun() -> lists:ukeysort(1, T) end},
     {umerge, fun() -> {lists:umerge([[1, 2], [2, 3]]), lists:umerge([1, 3], [1, 2]),
                        lists:umerge(fun(A, B) -> A =< B end, [1, 3], [3, 4]),
                        lists:umerge3([1], [1, 2], [2, 3]),
                        lists:rumerge([3, 1], [3, 2]),
                        lists:rumerge(fun(A, B) -> A >= B end, [3, 1], [2]),
                        lists:rumerge3([3], [2], [2, 1])} end},
     {uniq, fun() -> {lists:uniq(L), lists:uniq(fun({K, _}) -> K end, T)} end},
     {unzip, fun() -> {lists:unzip([{1, a}, {2, b}]), lists:unzip3([{1, a, x}, {2, b, y}])} end},
     {usort, fun() -> {lists:usort(L), lists:usort(fun(A, B) -> A >= B end, L),
                       lists:usort([1, 1.0, 1])} end},
     {zf, fun() -> lists:zf(fun(X) -> X > 5 end, L) end},
     {zip, fun() -> {lists:zip([1, 2], [a, b]), lists:zip([1, 2, 3], [a], trim),
                     lists:zip([1], [a, b], {pad, {x, y}}), lists:zip3([1], [2], [3]),
                     lists:zip3([1, 2], [a], [x, y], {pad, {p, q, r}})} end},
     {zip_bad, fun() -> lists:zip([1, 2], [a]) end},
     {zipwith, fun() -> {lists:zipwith(fun(A, B) -> A + B end, [1, 2], [10, 20]),
                         lists:zipwith(fun(A, B) -> {A, B} end, [1, 2], [a], trim),
                         lists:zipwith3(fun(A, B, C) -> A + B + C end, [1], [2], [3]),
                         lists:zipwith3(fun(A, B, C) -> [A, B, C] end, [1, 2], [a], [x], {pad, {p, q, r}})} end},
     {thing_to_list, fun() -> lists:concat([1.5, abc, "d", 7]) end},
     {badfun, fun() -> lists:map(not_a_fun, [1]) end},
     {badarity, fun() -> lists:map(fun(A, B) -> {A, B} end, [1]) end},
     {direct_badfun, fun() -> call1(not_a_fun) end},
     {direct_badarity, fun() ->
         try call1(fun(A, B) -> {A, B} end)
         catch error:{badarity, {F, Args}} when is_function(F, 2) -> {badarity, Args}
         end end},
     {long, fun() -> N = 20000, Seq = lists:seq(1, N),
                     {lists:sum(Seq), length(lists:reverse(Seq)), lists:last(lists:sort(lists:reverse(Seq))),
                      lists:foldl(fun(X, Acc) -> X + Acc end, 0, lists:map(fun(X) -> X * 2 end, Seq))} end}].

call1(F) -> F(1).
